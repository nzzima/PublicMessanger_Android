package com.nzzima.secretmessanger

/**
 * Отказ сервера с текстом — для проверок, где текст доходит до экрана.
 *
 * Тип нужен вместо `IllegalStateException` из-за правила в
 * [com.nzzima.secretmessanger.utils.errors.ErrorText]: чужому исключению текст не доверяется,
 * потому что он был бы английским. Это исключение лежит в наших пакетах, и разбор отдаёт его
 * текст как есть — ровно так же, как поступит с `CannotErase` или `LoginTaken` в бою.
 *
 * Без текста ([message] не передан) проверяется вторая половина того же правила: своё исключение
 * без сообщения показывается общей фразой, а не пустой строкой.
 */
class Refused(message: String? = null) : Exception(message)
