package com.nzzima.secretmessanger.lock.domain.api

/** Замок приложения: подтверждение, что телефон в руках у владельца. */
interface BiometricGate {

    /**
     * Есть ли чем подтвердить — биометрия или код-пароль устройства.
     *
     * Спрашивается **той же** меркой, которой потом идёт проверка. Расхождение этих двух
     * условий заперло iOS-приложение наглухо 24.08.2026: проверка шла по «биометрия или
     * код-пароль», а выполнение — по «только биометрия», и человек без настроенного Face ID
     * получал «попробуйте снова» столько раз, сколько готов был нажимать.
     */
    fun isAvailable(): Boolean
}
