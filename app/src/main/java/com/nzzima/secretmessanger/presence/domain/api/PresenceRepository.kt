package com.nzzima.secretmessanger.presence.domain.api

import com.nzzima.secretmessanger.presence.domain.models.Presence
import kotlinx.coroutines.flow.Flow

/**
 * Присутствие — отдельная коллекция, документ на человека.
 *
 * ```
 * presence/{uid}   lastSeen: Timestamp   — серверное время последнего удара
 * ```
 *
 * Отдельно от `users/{uid}` по той же причине, по которой отдельно лежат аватары:
 * «Контакты» держат слушатель на **всю** коллекцию профилей и перечитывают её при любом
 * изменении любого из них. Удар пульса раз в полминуты от каждого человека означал бы
 * перерисовку списка у всех и у каждого — вместе с перезаказом аватаров, то есть шторм из
 * ничего. Вторая причина мельче: правило записи в профиль требует `ownsLogin()`, а это
 * лишнее чтение реестра логинов на **каждый** удар.
 */
interface PresenceRepository {

    /**
     * Присутствие всех — целым снимком на каждое изменение. Нужно «Контактам».
     *
     * Коллекция целиком, потому что сегодня это десятки человек. На сотнях активных это
     * станет заметно, и тогда слушатель меняется на запрос-окно «кто отмечался за последнюю
     * минуту» с перезапуском раз в полминуты: в ответ приезжают только сетевые, а их всегда
     * меньше, чем всех.
     */
    fun observeEveryone(): Flow<Result<Map<String, Presence>>>

    /** Присутствие одного [uid]; `null` — он не отмечался ни разу. Нужно профилю и шапке. */
    fun observe(uid: String): Flow<Result<Presence?>>

    /**
     * Отмечает удар пульса аккаунта [uid].
     *
     * Время ставит **сервер**: правило требует `lastSeen == request.time`, и это не сверка
     * ради порядка — с клиентским временем «в сети» рисуется себе руками переводом часов, а
     * задним числом можно объявить себя офлайном и читать сообщения незаметно.
     */
    suspend fun beat(uid: String): Result<Unit>
}
