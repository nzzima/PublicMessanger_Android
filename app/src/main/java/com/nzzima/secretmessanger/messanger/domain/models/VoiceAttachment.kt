 * кто-то нажмёт «слушать», а файла к этому моменту ещё нет.
 *
 * Версия ключа приложена к вложению по той же причине, что у снимка: голосовое, записанное до
 * ротации, открывается прежним ключом. На iOS это было дефектом — там брали текущую версию.
 */
data class VoiceAttachment(val seconds: Double, val keyVersion: Int)
