package com.nzzima.secretmessanger.messanger.domain.api

import com.nzzima.secretmessanger.messanger.domain.models.Message
import kotlinx.coroutines.flow.Flow

/** Реплики из подколлекции `conversation/{id}/messages`. */
interface MessageRepository {

    /**
     * Последние [limit] реплик диалога [convoId], от старых к свежим, — целым снимком на
     * каждое изменение любой из них.
     *
     * Окно берётся с конца: первые [limit] были бы самыми старыми репликами переписки.
     *
     * Отказ приходит последним значением, после чего поток закрывается: слушатель
     * Firestore после ошибки снимается сам.
     */
    fun observeLast(convoId: String, limit: Long): Flow<Result<List<Message>>>

    /**
     * Отправляет [message] в диалог [convoId].
     *
     * Пишет две записи: сперва шапку — последнюю реплику, её время, признак шифрования и
     * версию ключа, — следом саму реплику. **Порядок обязателен**: правила проверяют
     * участие по составу из шапки, читая её через `get()`, и запись реплики опирается на
     * то, что шапка уже на месте.
     *
     * Шапка обновляется тем же шифротекстом, что лежит в реплике: оставь её открытой, и
     * последняя реплика каждого диалога лежала бы в базе читаемой.
     *
     * Состав участников и ключи этой записью не трогаются — их правит только создатель
     * диалога, и слепое слияние отклонили бы правила.
     */
    suspend fun send(convoId: String, message: Message): Result<Unit>
}
