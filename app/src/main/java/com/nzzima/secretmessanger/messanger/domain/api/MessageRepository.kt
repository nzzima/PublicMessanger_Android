package com.nzzima.secretmessanger.messanger.domain.api

import com.nzzima.secretmessanger.messanger.domain.models.Message
import kotlinx.coroutines.flow.Flow

/** Реплики из подколлекции `conversation/{id}/messages`. */
interface MessageRepository {

    /**
     * Последние [limit] реплик диалога [convoId], от старых к свежим, — целым снимком на
     * каждое изменение любой из них.
     *
     * Окно берётся с конца: первые [limit] были бы самыми старыми репликами переписки.
     *
     * Отказ приходит последним значением, после чего поток закрывается: слушатель
     * Firestore после ошибки снимается сам.
     */
    fun observeLast(convoId: String, limit: Long): Flow<Result<List<Message>>>

    /**
     * Отправляет [message] в диалог [convoId].
     *
     * Пишет две записи: сперва шапку — последнюю реплику, её время, признак шифрования и
     * версию ключа, — следом саму реплику. **Порядок обязателен**: правила проверяют
     * участие по составу из шапки, читая её через `get()`, и запись реплики опирается на
     * то, что шапка уже на месте.
     *
     * Шапка обновляется шифротекстом, а не открытым текстом: оставь его открытым, и
     * последняя реплика каждого диалога лежала бы в базе читаемой.
     *
     * Состав участников и ключи этой записью не трогаются — их правит только создатель
     * диалога, и слепое слияние отклонили бы правила.
     *
     * @param preview то, что увидит список диалогов, — уже запечатанное. Отдельным доводом,
     *   потому что у точки на карте оно не совпадает с телом реплики: в теле координаты, а в
     *   списке «📍 Геопозиция». У текста и снимка совпадает.
     */
    suspend fun send(convoId: String, message: Message, preview: String): Result<Unit>

    /**
     * Дописывает в ленту [convoId] отметку о смене ключа от [senderId].
     *
     * Ни текста, ни признака шифрования: шифровать в ней нечего, поле `type` и есть всё
     * сообщение. **Шапку она не трогает** — список диалогов должен показывать последнюю
     * настоящую реплику, а не служебную запись.
     */
    suspend fun note(convoId: String, senderId: String): Result<Unit>

    /**
     * Стирает страницу реплик диалога [convoId] вместе с их вложениями.
     *
     * Страницами, а не целиком: батч Firestore держит 500 операций, а на реплику их уходит
     * до двух — сама реплика и её вложение.
     *
     * **Вложения не перечисляются запросом, а выводятся из реплик.** Идентификатор документа
     * в `audio` и `images` равен идентификатору реплики, а сам документ — это байты записи
     * или снимка: перечислить подколлекцию значило бы скачать все мегабайты диалога ради
     * одних имён. Реплика называет своё вложение полем `type` и весит строку. Плата —
     * осиротевшее вложение, если байты записались, а реплика следом за ними нет; такой мусор
     * редкий и тихий, и он дешевле гарантированной выкачки всего.
     *
     * @return сколько реплик стёрто; `0` — не осталось ни одной, и повторять нечего.
     */
    suspend fun erasePage(convoId: String, limit: Long): Result<Int>
}
