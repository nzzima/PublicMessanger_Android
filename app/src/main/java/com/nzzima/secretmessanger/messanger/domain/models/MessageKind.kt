package com.nzzima.secretmessanger.messanger.domain.models

/**
 * Вид реплики — поле `type` документа.
 *
 * Отсутствие поля означает [Text]: текстовая реплика его не пишет, и так же читает iOS.
 * Незнакомый вид тоже читается как [Text] — реплика останется в ленте, а не пропадёт.
 */
enum class MessageKind {

    /** Текст, единственный вид, который Android умеет отправлять. */
    Text,

    /** Голосовое: байты лежат в подколлекции `audio`, здесь только длительность. */
    Voice,

    /** Снимок: байты лежат в подколлекции `images`, здесь только размеры. */
    Photo,

    /** Точка на карте: две координаты на месте текста, зашифрованные как текст. */
    Location,

    /**
     * Отметка о смене ключа диалога.
     *
     * Единственная реплика, которую никто не писал: её кладёт создатель группы, удаляя
     * участника. Содержимого у неё нет — с этого места переписка запечатана другим ключом.
     */
    KeyNotice,
}
