package com.nzzima.secretmessanger.voice.domain.api

import com.nzzima.secretmessanger.voice.domain.models.Recording

/**
 * Запись голосового с микрофона.
 *
 * Потолок длительности держит сам рекордер, а не интерфейс: упереться в лимит документа
 * значит потерять уже наговорённое в момент отправки, а не предупредить заранее.
 */
interface VoiceRecorder {

    /** Идёт ли запись прямо сейчас. */
    val isRecording: Boolean

    /**
     * Начинает запись.
     *
     * Разрешение на микрофон спрашивает экран: спрашивать умеет только `Activity`, и тащить
     * её сюда значило бы тащить платформу в домен.
     *
     * @return `false`, если микрофон занят или записывать некуда.
     */
    fun start(): Boolean

    /**
     * Останавливает запись и отдаёт записанное.
     *
     * @return `null`, если записи не было либо она оборвалась слишком рано, чтобы в файле
     *   оказался звук: нажатие вместо удержания — обычное дело, и отправлять из него нечего.
     */
    fun stop(): Recording?

    /** Бросает запись и убирает файл: отправлять её человек передумал. */
    fun cancel()
}
