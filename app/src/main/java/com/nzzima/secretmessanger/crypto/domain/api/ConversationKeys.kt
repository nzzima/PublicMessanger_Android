package com.nzzima.secretmessanger.crypto.domain.api

/**
 * Ключи диалогов.
 *
 * Ключ диалога симметричный, один на всех участников, и лежит в шапке `conversation/{id}`
 * запечатанным каждому участнику отдельно:
 *
 *     convoKeys: { "<uid>_<версия>": "<эфемерный открытый ключ>.<запечатанный ключ>" }
 *     keyVersion: <текущая версия>
 *
 * Поле называется `convoKeys`, а не `keys`: `keys()` — метод карты в правилах Firestore.
 *
 * Версии заводятся при ротации — удалили участника, завели новый ключ, а старые остались
 * в шапке, чтобы уже написанное читалось. Каждое сообщение помнит свою версию.
 *
 * Формат общий с iOS (`ConversationCrypto.swift`), менять его нельзя.
 */
interface ConversationKeys {

    /**
     * Ключ диалога [convoId] версии [version] для аккаунта [uid] — 32 байта.
     *
     * @param entries карта `convoKeys` из шапки диалога.
     * @return `null`, если записи для нас в карте нет, постоянного ключа аккаунта на этом
     *   устройстве нет либо запись запечатана для другой пары ключей. Последнее
     *   невосстановимо: диалог этим устройством не откроется никогда.
     */
    fun open(convoId: String, uid: String, version: Int, entries: Map<String, String>): ByteArray?

    /**
     * Новый ключ диалога [convoId], запечатанный каждому участнику отдельно.
     *
     * Версия у нового диалога всегда первая: ротации заводит тот, кто правит состав, а
     * состав Android не правит.
     *
     * @param publicKeys uid → открытая половина участника в base64.
     * @return готовые записи для карты `convoKeys`; `null`, если хоть одна половина не
     *   разобралась. Всё или ничего: участник, оставшийся без записи, не прочитает диалог
     *   никогда — дозапечатывания, как у iOS, в Android нет.
     */
    fun sealNew(convoId: String, publicKeys: Map<String, String>): Map<String, String>?
}
