package com.nzzima.secretmessanger.utils.media

/**
 * Во сколько раз уменьшать картинку при чтении: наибольшая степень двойки, при которой
 * сторона [source] остаётся не меньше [target].
 *
 * Нужна и аватарам, и снимкам переписки: без неё в память ехал бы кадр целиком — двенадцать
 * мегапикселей ради кружка в 320 точек или пузыря в 1280.
 *
 * Обрыв перебора — `takeWhile`, а не отбор годного из всей последовательности: она
 * бесконечна, и перебор целиком доходил до переполнения `Int`, а следом до деления на ноль.
 */
internal fun sampleSize(source: Int, target: Int): Int =
    generateSequence(1) { it * 2 }
        .takeWhile { it == 1 || source / it >= target }
        .last()
