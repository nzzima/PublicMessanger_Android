package com.nzzima.secretmessanger.auth.domain.api

/**
 * Идущая регистрация — для тех, кому её надо переждать.
 *
 * Регистрация открывает сессию первым шагом (аккаунтом), а профиль пишет третьим. В
 * промежутке профиля в базе нет, и всякий, кто судит по нему об аккаунте, обязан сперва
 * дождаться конца: иначе обычная регистрация выглядит как оборванная.
 */
interface RegistrationProgress {

    /** Возвращается, когда регистрация не идёт. Если не идёт и сейчас — немедленно. */
    suspend fun awaitIdle()
}
