package com.nzzima.secretmessanger.avatar.domain.api

/** Аватары для показа и правки. */
interface AvatarInteractor {

    /**
     * Аватар аккаунта [uid] версии [version]; `null` — показать заглушку.
     *
     * Нулевая версия означает «аватара нет», и в базу за ним никто не идёт: ради этого
     * маркер в профиле и заведён — иначе каждый человек без аватара стоил бы промаха в
     * Firestore при каждом показе списка.
     *
     * Уже прочитанное берётся из памяти по паре «кто + версия»: сменившийся аватар получает
     * новую версию, поэтому устареть кэш не может.
     */
    suspend fun avatar(uid: String, version: Int): ByteArray?

    /**
     * Ставит аккаунту [uid] картинку [source] взамен версии [currentVersion].
     *
     * Пишется сначала картинка, потом маркер в профиле — тот же порядок, что у голосовых на
     * iOS: сперва то, за чем пойдут, потом объявление, что оно есть. Обратный порядок
     * означал бы маркер, ведущий в пустоту, и заглушку вместо аватара у всех, кто успел
     * прочитать профиль.
     *
     * @return отказ [com.nzzima.secretmessanger.avatar.domain.models.AvatarTooLarge], если
     *   картинку не удалось подготовить; в базу при этом не уходит ничего.
     */
    suspend fun change(uid: String, source: String, currentVersion: Int): Result<Unit>

    /** Убирает аватар аккаунта [uid]: сперва картинку, следом маркер в профиле. */
    suspend fun remove(uid: String): Result<Unit>
}
