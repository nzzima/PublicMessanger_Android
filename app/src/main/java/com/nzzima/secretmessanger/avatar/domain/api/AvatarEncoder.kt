package com.nzzima.secretmessanger.avatar.domain.api

/** Подготовка выбранной картинки к тому, чтобы стать аватаром. */
interface AvatarEncoder {

    /**
     * Обрезает картинку [source] в квадрат по центру, ужимает до стороны
     * [com.nzzima.secretmessanger.utils.constants.Constants.AVATAR_SIDE] и кодирует в JPEG.
     *
     * Обрезка, а не сжатие в квадрат: сплющенное лицо хуже обрезанного. Квадрат заранее —
     * потому что показывается аватар всегда в круге, и байты за невидимые углы платились бы
     * при каждой загрузке.
     *
     * @param source адрес выбранной картинки в том виде, в каком его отдал системный
     *   выборщик; разбирать его — дело слоя данных.
     * @return `null`, если картинка не разобралась или не уместилась в бюджет.
     */
    suspend fun encode(source: String): ByteArray?
}
