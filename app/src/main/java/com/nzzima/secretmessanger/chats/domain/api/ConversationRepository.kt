package com.nzzima.secretmessanger.chats.domain.api

import com.nzzima.secretmessanger.chats.domain.models.Chat
import com.nzzima.secretmessanger.chats.domain.models.ConversationGone
import com.nzzima.secretmessanger.chats.domain.models.ConversationHeader
import com.nzzima.secretmessanger.chats.domain.models.Moment
import kotlinx.coroutines.flow.Flow

/** Шапки диалогов из коллекции `conversation`. */
interface ConversationRepository {

    /**
     * Диалоги, где состоит [selfId], — целым снимком на каждое изменение любого из них.
     *
     * Порядок произвольный: сортирует вызывающий. Пара `arrayContains` + `orderBy` требует
     * составного индекса, которого в базе нет.
     *
     * Снимок отдаётся целиком, а не изменениями: шапка меняется на каждой отправке, и
     * список всё равно пересобирается заново.
     *
     * Отказ приходит последним значением, после чего поток закрывается: слушатель Firestore
     * после ошибки снимается сам, и продолжать слушать уже нечего — за повторной попыткой
     * нужна новая подписка.
     */
    fun observeHeaders(selfId: String): Flow<Result<List<ConversationHeader>>>

    /**
     * Один диалог [convoId] — свежим значением на каждое изменение его шапки.
     *
     * Слушается, а не читается однократно: состав, имена участников и ключи меняются при
     * открытом экране — добавленному участнику ключ дозапечатывают, и приезжает он сюда.
     *
     * Последняя реплика в [Chat] не входит: экрану переписки она не нужна, там есть сами
     * реплики.
     *
     * Отказ приходит последним значением, после чего поток закрывается — как и у
     * [observeHeaders]. Исчезнувшая шапка приходит [ConversationGone]: диалог стёрли, и
     * повторная подписка ничего не вернёт.
     */
    fun observeChat(convoId: String, selfId: String): Flow<Result<Chat>>

    /**
     * Диалог [convoId] одним чтением; `null` — доступной нам шапки нет.
     *
     * Нужно перед заведением: писать новую шапку поверх существующей нельзя — правила
     * читают такую запись как изменение состава и отклоняют её целиком.
     *
     * «Нет» здесь шире, чем «документа не существует»: отказ по правам возвращается тем же
     * `null`. Правило чтения сверяет состав по `resource.data`, а у несуществующего
     * документа `resource` пуст, поэтому чтение отсутствующей шапки отказывает так же, как
     * чтение чужой. Различать их нечем и незачем — оба исхода ведут к попытке завести
     * диалог, а чужую шапку правила перезаписать не дадут. Отказ связи по-прежнему
     * приходит отказом.
     */
    suspend fun existing(convoId: String, selfId: String): Result<Chat?>

    /**
     * Заводит шапку диалога: состав, создатель, имена участников и раздача ключа.
     *
     * Последней реплики в новой шапке нет намеренно: диалог на двоих заводится при первом
     * же открытии из «Контактов», и с непустым превью список «Чаты» превратился бы в
     * историю просмотров — строка появлялась бы у всякого, чей профиль открыли. Так же
     * заводит iOS.
     */
    suspend fun create(chat: Chat): Result<Unit>

    /**
     * Отмечает, что аккаунт [uid] дочитал диалог [convoId] до момента [upTo].
     *
     * Пишется дозаписью в карту `readUpTo` шапки: чужие отметки остаются на месте, и на это
     * же опирается правило — оно требует, чтобы в карте изменился ровно свой ключ и ничей
     * больше. Без такой проверки участник проставлял бы прочтение за другого, и это не
     * косметика: человек ждал бы ответа, считая, что его прочли.
     *
     * [upTo] — момент **реплики**, а не «сейчас»: так обе стороны сравнивают числа с одних
     * часов, отправительских.
     */
    suspend fun markRead(convoId: String, uid: String, upTo: Moment): Result<Unit>

    /**
     * Проставляет имя [login] аккаунта [uid] в шапках **всех** его диалогов.
     *
     * Разовый проход после переименования. Карта `logins` в шапке — кэш имён, и без такого
     * прохода переименовавшийся остался бы под старым именем во всех диалогах, а узнал бы об
     * этом разве что от собеседника.
     *
     * Правила пропускают это как обычную запись участника: состав, создатель, ключи и чужие
     * отметки прочтения не тронуты — ровно то же самое делает отправка реплики.
     *
     * Пишется батчем: диалогов может быть много, а растягивать переименование на десятки
     * отдельных запросов незачем.
     */
    suspend fun renameInConversations(uid: String, login: String): Result<Unit>

    /**
     * Вычёркивает [uid] из состава диалога [convoId], оставляя [members] без него.
     *
     * Единственная запись состава, которую делает **не создатель**, и правило под неё
     * отдельное: вычеркнуть разрешено ровно себя, а владельцу выход закрыт вовсе — группа
     * осталась бы без того, кто правит состав.
     *
     * Ключи, создатель и метки прочтения при этом не трогаются: правило сверяет и их.
     */
    suspend fun leave(convoId: String, uid: String, members: List<String>): Result<Unit>
}
