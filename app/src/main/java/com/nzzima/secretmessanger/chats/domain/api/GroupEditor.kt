package com.nzzima.secretmessanger.chats.domain.api

import com.nzzima.secretmessanger.chats.domain.models.Chat
import kotlinx.coroutines.flow.Flow

/**
 * Правка состава группы — работа создателя, и только его: правила пропускают запись состава
 * лишь автору диалога.
 */
interface GroupEditor {

    /**
     * Шапка диалога [convoId] глазами [selfId] — свежим значением на каждое изменение.
     *
     * Свой слушатель, а не состав, переданный с экрана переписки: список участников обязан
     * обновляться и у того, кто просто смотрит его, пока состав меняет кто-то другой.
     */
    fun observe(convoId: String, selfId: String): Flow<Result<Chat>>

    /**
     * Добавляет [members] (карта «uid → имя») в группу [chat].
     *
     * Добавленному раздаются **все версии** ключа, какие мы можем открыть сами: правила и так
     * дают ему прочитать историю, а без старых ключей он увидел бы вместо неё стену
     * нерасшифрованного.
     *
     * Ключ при добавлении **не ротируется**: новый участник и так получает доступ ко всему
     * написанному, и менять ключ ради него значило бы перевыпускать его на ровном месте.
     *
     * @return отказ [com.nzzima.secretmessanger.chats.domain.models.CompanionKeyMissing], если
     *   у кого-то из добавляемых нет опубликованного ключа: в Android дозапечатывания нет, и
     *   человек остался бы в группе, не видя ни строчки.
     */
    suspend fun add(chat: Chat, members: Map<String, String>): Result<Unit>

    /**
     * Убирает [uid] из группы [chat] и **перевыпускает ключ** для оставшихся.
     *
     * Ротация обязательна: правила закроют удалённому доступ к диалогу, но ключ, которым
     * шифровались сообщения, останется у него на руках навсегда — без нового он остался бы
     * криптографически способен читать всё, что напишут дальше.
     *
     * Имя удалённого из карты `logins` не вычищается: названию и подписям оно не мешает (те
     * собираются по составу) и пригодится, если человека вернут.
     *
     * После смены ключа в ленту дописывается отметка — рассказ о событии, а не само событие:
     * её неудача ничего не отменяет и человеку не показывается.
     */
    suspend fun remove(chat: Chat, uid: String): Result<Unit>
}
