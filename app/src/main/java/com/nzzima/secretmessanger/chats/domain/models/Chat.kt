package com.nzzima.secretmessanger.chats.domain.models

/**
 * Переписка: с кем она и чем шифруется.
 *
 * Ни названия, ни признака группы в базе нет — и то и другое выводится из состава.
 *
 * @property id идентификатор шапки `conversation/{id}`.
 * @property members участники; [selfId] входит в них всегда.
 * @property logins кэш имён участников из шапки: uid → логин.
 * @property owner создатель, единственный, кто меняет состав. Пусто у диалогов,
 *   заведённых до появления поля: состав в них не меняет никто.
 * @property selfId владелец текущей сессии.
 * @property convoKeys ключ диалога, запечатанный каждому участнику; см.
 *   [com.nzzima.secretmessanger.crypto.domain.api.ConversationKeys].
 * @property keyVersion текущая версия ключа диалога.
 * @property readUpTo докуда каждый участник дочитал. Метка живёт в шапке, а не в самих
 *   репликах, и это следствие правил: на `messages/{id}` стоит `allow update: if false` —
 *   отправленное неизменяемо. Карта в шапке обходится одной записью вместо записи на каждую
 *   прочитанную реплику. Диалоги, заведённые до появления меток, карты не имеют вовсе.
 */
data class Chat(
    val id: String,
    val members: List<String>,
    val logins: Map<String, String>,
    val owner: String,
    val selfId: String,
    val convoKeys: Map<String, String>,
    val keyVersion: Int,
    val readUpTo: Map<String, Moment> = emptyMap(),
) {

    /** Группа — больше двух участников. */
    val isGroup: Boolean get() = members.size > 2

    /**
     * Шифруется ли переписка.
     *
     * Пустая карта ключей означает диалог, начатый до появления шифрования: его история
     * лежит в базе открытой, и новые реплики уходят туда же открытыми — задним числом
     * их не зашифровать. Так же читает iOS.
     */
    val isEncrypted: Boolean get() = convoKeys.isNotEmpty()

    /**
     * Название — логины всех, кроме себя.
     *
     * Участник, чьего логина в кэше шапки нет, из названия выпадает.
     */
    val title: String get() = members.filter { it != selfId }.mapNotNull(logins::get).joinToString(", ")

    /**
     * Собеседник в диалоге на двоих; `null` у группы.
     *
     * `null` здесь означает не «нет собеседника», а «одним его не назвать»: участников
     * несколько, и выбирать из них одного было бы враньём.
     */
    val companionId: String? get() = if (isGroup) null else members.firstOrNull { it != selfId }

    /**
     * Прочитали ли реплику [date] **все**, кроме её автора.
     *
     * В группе «прочитали двое из пятерых» пришлось бы куда-то поместить, а действий из этой
     * цифры не следует никаких: дописывать некому, ждать нечего. Две галочки, когда дошло до
     * последнего, — единственная форма, у которой есть смысл.
     *
     * Сравнение идёт по дате **реплики**, а не по времени, когда её прочли: читающий
     * возвращает ту же дату, что стоит в документе, поэтому обе стороны сравнивают числа с
     * одних часов — отправительских. Со временем чтения разошедшиеся часы двух телефонов
     * давали бы то галочки на непрочитанном, то их отсутствие на прочитанном.
     *
     * Диалог, в котором кроме автора никого нет, прочитанным не считается: подтвердить некому.
     */
    fun isRead(date: Moment, author: String): Boolean {
        val others = members.filter { it != author }

        return others.isNotEmpty() && others.all { member ->
            readUpTo[member]?.let { it >= date } == true
        }
    }

    companion object {

        /**
         * Идентификатор диалога на двоих — пара uid по алфавиту через подчёркивание.
         *
         * Детерминированный намеренно: оба собеседника независимо приходят к одному и тому
         * же идентификатору, поэтому диалог, открытый из «Контактов», попадает в
         * существующий, а не заводит второй. У группы состав в идентификатор не
         * закодируешь, и там он случайный: две группы одним составом — это два разных
         * разговора, а не один и тот же.
         *
         * Формат общий с iOS (`Chat.conversationId`), менять его нельзя.
         */
        fun conversationId(first: String, second: String): String =
            listOf(first, second).sorted().joinToString("_")
    }
}
