package com.nzzima.secretmessanger.chats.domain.api

import com.nzzima.secretmessanger.chats.domain.models.Chat

/**
 * Удаление переписки.
 *
 * Стирает **у всех участников**, а не прячет у себя: мессенджер, называющий себя секретным,
 * прятать не должен — слово «удалить» значит здесь стирание.
 */
interface ChatEraser {

    /**
     * Стирает переписку [chat] целиком: сперва реплики с вложениями, шапку последней.
     *
     * Порядок обязателен. Правила на подколлекции читают состав участников из шапки через
     * `get()`, а `get()` по несуществующему документу роняет проверку целиком: стёртая первой
     * шапка оставила бы вложения в базе навсегда — недоступными ни для чтения, ни для
     * удаления **никому**, включая владельца проекта.
     *
     * Оборвалось на середине — шапка на месте, диалог остался в списке, повтор доделывает
     * начатое. Половина переписки к тому моменту стёрта, и это всё равно лучше недостижимого
     * мусора.
     *
     * @return отказ [com.nzzima.secretmessanger.chats.domain.models.CannotErase], если стирать
     *   нам не положено, — см. [Chat.canErase].
     */
    suspend fun erase(chat: Chat): Result<Unit>
}
